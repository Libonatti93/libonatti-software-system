const html = document.documentElement;
const languageButtons = document.querySelectorAll(".lang");

function setLanguage(language) {
  const dictionary = translations[language];
  if (!dictionary) return;

  html.lang = language === "pt" ? "pt-BR" : language;
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = dictionary[element.dataset.i18n];
    if (value) element.textContent = value;
  });

  languageButtons.forEach((button) => {
    const active = button.dataset.lang === language;
    button.classList.toggle("active", active);
    if (active) button.setAttribute("aria-current", "page");
    else button.removeAttribute("aria-current");
  });

  const locale = { pt: "pt-br", es: "es", en: "en" }[language];
  document.querySelectorAll("[data-localized-link='blog']").forEach((link) => {
    link.href = `/${locale}/blog/`;
  });
  const casePath = {
    pt: "/pt-br/projetos/nogueira-cardiologia/",
    es: "/es/proyectos/nogueira-cardiologia/",
    en: "/en/projects/nogueira-cardiologia/"
  }[language];
  document.querySelectorAll("[data-localized-link='nogueira-case']").forEach((link) => {
    link.href = casePath;
  });
}

const pathLanguage = location.pathname.startsWith("/es")
  ? "es"
  : location.pathname.startsWith("/en")
    ? "en"
    : "pt";
setLanguage(pathLanguage);

const menuButton = document.querySelector(".menu-button");
const mobileMenu = document.querySelector(".mobile-menu");

function closeMenu() {
  menuButton.setAttribute("aria-expanded", "false");
  mobileMenu.classList.remove("open");
  mobileMenu.setAttribute("aria-hidden", "true");
  document.body.classList.remove("menu-open");
}

menuButton.addEventListener("click", () => {
  const opening = menuButton.getAttribute("aria-expanded") !== "true";
  menuButton.setAttribute("aria-expanded", String(opening));
  mobileMenu.classList.toggle("open", opening);
  mobileMenu.setAttribute("aria-hidden", String(!opening));
  document.body.classList.toggle("menu-open", opening);
});

mobileMenu.querySelectorAll("a").forEach((link) => link.addEventListener("click", closeMenu));

const revealObserver = new IntersectionObserver(
  (entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("visible");
        revealObserver.unobserve(entry.target);
      }
    });
  },
  { threshold: 0.12 }
);

document.querySelectorAll(".reveal").forEach((element) => revealObserver.observe(element));

function updateClock() {
  const time = new Intl.DateTimeFormat("pt-BR", {
    timeZone: "America/Sao_Paulo",
    hour: "2-digit",
    minute: "2-digit",
    hour12: false
  }).format(new Date());
  document.querySelector("#clock").textContent = time;
}

document.querySelector("#year").textContent = new Date().getFullYear();
updateClock();
setInterval(updateClock, 60_000);
